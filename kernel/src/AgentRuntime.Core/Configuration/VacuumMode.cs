namespace AgentRuntime.Core.Configuration;

/// <summary>
/// **真空模式（Vacuum Mode）** —— **纯消融对照专用**：前缀里**什么都没有**，只有本 turn 的用户消息。
/// <para>
/// 与裸聊（<c>--bare</c>）的关系：裸聊**还穿着协议**（协议区 R1-P + 本轮用户消息），真空**连协议都不给**
/// ——「裸聊还穿着内衣，真空连内衣都没有」。
/// </para>
/// <para>
/// <b>它是 P3 闸门（协议不可摘）的唯一天然例外</b>，而且这个例外**不是用户可选档位**：
/// 它是做消融实验的**对照装置**（证明「协议区 + 模块」各自的成本与价值）。
/// 因此本模式**不保证**自报与接续：没有协议，模型不知道 <c>[FOCUS]</c> / <c>[TAIL]</c> 怎么写，
/// 跨轮状态无处表达 —— 这正是它作为**下界对照**的意义。
/// </para>
/// </summary>
public enum VacuumMode
{
    /// <summary>正常模式（默认）：协议区强制装配，业务模块按配置装配。</summary>
    Off = 0,

    /// <summary>真空模式：一条 system 都没有（连协议区都不挂）。消融对照专用。</summary>
    On = 1,
}
